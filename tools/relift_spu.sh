#!/bin/sh
# Lift every SPU program LittleBigPlanet runs into src/spu_gen (git-ignored):
#  - the SPU ELFs embedded in the EBOOT (FMOD, Bink, voice DSPs),
#  - the WWS job-manager SPURS policy module (a raw blob in the EBOOT),
#  - the WWS job modules shipped compressed inside data.sdat.
set -e
PY="${PYTHON:-python3}"
T=ps3recomp/tools
mkdir -p analysis src/spu_gen
rm -rf src/spu_gen/*

# ---- SPU ELFs in the EBOOT --------------------------------------------------
rm -rf analysis/spu
"$PY" "$T/extract_spu_images.py" game/EBOOT.elf --out analysis/spu
"$PY" "$T/build_spu_workloads.py" --images analysis/spu --lifted src/spu_gen \
    --out src/spu_gen/spu_workloads.c \
    --register-fn lbp_spu_register_all --constructor --title lbp --return-entries

# ---- WWS policy module: 11520 raw bytes at 0x8C1D00, resident at LS 0xA00 ----
"$PY" -I - <<'PYEOF'
import struct
d = open("game/EBOOT.elf", "rb").read()
ph = struct.unpack_from(">Q", d, 0x20)[0]
for i in range(struct.unpack_from(">H", d, 0x38)[0]):
    t, f, off, va, pa, fs, ms, al = struct.unpack_from(">IIQQQQQQ", d, ph + i * 56)
    if t == 1 and va <= 0x8C1D00 < va + fs:
        open("analysis/pm_wws.bin", "wb").write(d[off + 0x8C1D00 - va:][:11520])
PYEOF
"$PY" "$T/find_spu_functions.py" analysis/pm_wws.bin --raw --base 0xA00 --out analysis/pm_wws_funcs.json
mkdir -p src/spu_gen/pm_wws
"$PY" "$T/spu_lifter.py" analysis/pm_wws.bin --base 0xA00 \
    --functions analysis/pm_wws_funcs.json --symbol-prefix pm_wws_ -o src/spu_gen/pm_wws
FP=$("$PY" -I -c "
h=1469598103934665603
for x in open('analysis/pm_wws.bin','rb').read(): h=((h^x)*1099511628211)&0xFFFFFFFFFFFFFFFF
print('0x%016X' % h)")
cat > src/spu_gen/pm_register.c <<CEOF
/* GENERATED by tools/relift_spu.sh: the lifted WWS job-manager policy module. */
#include "spu_workload.h"
extern void spu_begin_image(int image_id);
extern void pm_wws_spu_func_00000A00(spu_context*);
extern void pm_wws_spu_recomp_register(void);
__attribute__((constructor)) static void lbp_pm_register(void)
{
    spu_begin_image(100);
    pm_wws_spu_recomp_register();
    spu_workload_register_img(${FP}ULL, pm_wws_spu_func_00000A00, 100, "pm_wws");
    spu_begin_image(0);
}
CEOF

# ---- WWS job modules from data.sdat ------------------------------------------
rm -rf analysis/jobmods && mkdir -p analysis/jobmods
"$PY" "$T/extract_jobmods.py" --usrdir disc/PS3_GAME/USRDIR --out analysis/jobmods
"$PY" "$T/lift_jobmods.py" --jobmods analysis/jobmods --out src/spu_gen/jobmods \
    --register src/spu_gen/jobmods_register.c

# ---- Raw SPURS job binaries embedded in the EBOOT (not ELFs, so the image
# scanner misses them). Loaded at LS 0 and entered there. --------------------
#   0x91D380, 175744 bytes: the voice-chat codec job (cellSpursJobMain2).
OUT=src/spu_gen/spu_jobs.c
{
  echo "/* GENERATED by tools/relift_spu.sh: raw SPURS job binaries from the EBOOT. */"
  echo "#include \"spu_workload.h\""
  echo "extern void spu_begin_image(int image_id);"
} > "$OUT.tmp"
REG=""; IMG=300
for J in 0x91D380:175744; do
    VA=${J%%:*}; LEN=${J##*:}; NAME=job_${VA#0x}
    "$PY" -I - "$VA" "$LEN" "analysis/$NAME.bin" <<'PYEOF'
import struct, sys
va, n, out = int(sys.argv[1], 16), int(sys.argv[2]), sys.argv[3]
d = open("game/EBOOT.elf", "rb").read()
ph = struct.unpack_from(">Q", d, 0x20)[0]
for i in range(struct.unpack_from(">H", d, 0x38)[0]):
    t, f, off, v, pa, fs, ms, al = struct.unpack_from(">IIQQQQQQ", d, ph + i * 56)
    if t == 1 and v <= va < v + fs:
        open(out, "wb").write(d[off + va - v:][:n])
PYEOF
    FP=$("$PY" -I -c "
h=1469598103934665603
for x in open('analysis/$NAME.bin','rb').read(): h=((h^x)*1099511628211)&0xFFFFFFFFFFFFFFFF
print('0x%016X' % h)")
    "$PY" "$T/find_spu_functions.py" "analysis/$NAME.bin" --raw --base 0 --out "analysis/${NAME}_funcs.json"
    mkdir -p "src/spu_gen/$NAME"
    "$PY" "$T/spu_lifter.py" "analysis/$NAME.bin" --base 0 --return-entries \
        --functions "analysis/${NAME}_funcs.json" --symbol-prefix "${NAME}_" -o "src/spu_gen/$NAME"
    echo "extern void ${NAME}_spu_func_00000000(spu_context*); extern void ${NAME}_spu_recomp_register(void);" >> "$OUT.tmp"
    REG="$REG    spu_begin_image($IMG); ${NAME}_spu_recomp_register();
    spu_workload_register_img(${FP}ULL, ${NAME}_spu_func_00000000, $IMG, \"$NAME\");
"
    IMG=$((IMG + 1))
done
{
  echo "__attribute__((constructor)) static void lbp_spu_jobs_register(void)"
  echo "{"
  printf "%s" "$REG"
  echo "    spu_begin_image(0);"
  echo "}"
} >> "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
